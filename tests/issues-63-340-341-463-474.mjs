import assert from 'node:assert/strict';
import fs from 'node:fs';
await import('../js/macho.js');
const M=globalThis.MachO;
assert.ok(M);
const source=fs.readFileSync('js/macho.js','utf8');
assert.match(source,/THREAD: 0x4/);
assert.match(source,/commandMinSize/);
assert.match(source,/section outside parent\/slice range/);
assert.match(source,/parseThreadEntrypoint/);
assert.match(source,/arm64_32/);
const funcs=M.parseFunctionStarts(Uint8Array.from([4,4,0]),0x1000n,{regions:[{exec:true,vmAddr:0x1000n,size:0x20n}],architecture:'arm64'});
assert.deepEqual(Array.from(funcs),[0x1004n,0x1008n]); assert.equal(funcs.complete,true);
const bad=M.parseFunctionStarts(Uint8Array.from([2,0]),0x1000n,{regions:[{exec:true,vmAddr:0x1000n,size:0x20n}],architecture:'arm64e'});
assert.equal(bad.length,0); assert.equal(bad.complete,false); assert.equal(bad.rejected,1);
const backend=fs.readFileSync('js/backend.js','utf8');
assert.match(backend,/pointerBits/); assert.match(backend,/pointer-authentication/); assert.match(backend,/ilp32-pointer-abi/);
const worker=fs.readFileSync('js/worker-legacy.js','utf8');
assert.match(worker,/info\.entry != null/); assert.match(worker,/list\.complete === true/);
console.log('Mach-O remaining issue guards passed');
