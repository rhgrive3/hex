import assert from 'node:assert/strict';
import fs from 'node:fs';
import { classifyCallArguments } from '../js/ir-core.js';
import { memoryOrigins, backwardSlice } from '../js/slice.js';
const unknown=classifyCallArguments({callTarget:0x1000n},{});
assert.equal(unknown.srcs.filter(x=>x.reg?.startsWith('x')).length,8);
assert.equal(unknown.srcs.filter(x=>x.reg?.startsWith('v')).length,8);
assert.equal(unknown.stackArgsUnknown,true);
assert.equal(unknown.stackArgsMayContainPointers,false);
const ninePtrs=classifyCallArguments({callTarget:0x1000n,callPrototype:{args:Array.from({length:9},()=>({type:'void *'}))}},{});
assert.equal(ninePtrs.stackArguments.length,1);
assert.equal(ninePtrs.stackArguments[0].pointer,true);
assert.equal(ninePtrs.stackArgsMayContainPointers,true);
const hfa=classifyCallArguments({callPrototype:{args:[{abiClass:'hfa',members:4,bits:32}]}},{});
assert.deepEqual(hfa.arguments[0].regs,['v0','v1','v2','v3']);
const s1={id:1,op:'store'},s2={id:2,op:'store'},s3={id:3,op:'store'},cl={id:4,op:'call'};
const nested={kind:'phi',incoming:[{node:{kind:'store',inst:s1}},{node:{kind:'phi',incoming:[{node:{kind:'store',inst:s2}},{node:{kind:'phi',incoming:[{node:{kind:'store',inst:s3}},{node:{kind:'clobber',inst:cl}}]}}]}}]};
const origins=memoryOrigins(nested,{maxNodes:32,maxEdges:32});
assert.deepEqual(new Set(origins.stores),new Set([s1,s2,s3]));
assert.deepEqual(origins.clobbers,[cl]);
assert.equal(origins.ambiguous,true); assert.equal(origins.branchDependent,true);
assert.equal(memoryOrigins(nested,{maxNodes:2,maxEdges:2}).truncated,true);
const load={id:20,op:'load',args:[],memUse:nested,row:10,block:0};
const sl=backwardSlice({instructions:[s1,s2,s3,cl,load]},load,{throughMemory:true,memoryNodeLimit:32,memoryEdgeLimit:32});
assert.equal(sl.memoryAmbiguous,true); assert.ok(sl.instructions.includes(s2)&&sl.instructions.includes(s3)&&sl.instructions.includes(cl));
const inter=fs.readFileSync('js/interproc.js','utf8');
assert.match(inter,/hasContextSensitiveSummaryInputs/);
assert.match(inter,/delete next\.returnEvidence/);
assert.match(inter,/delete next\.returnsValue/);
assert.match(inter,/cacheScopeOf\(this\.context\)/);
const core=fs.readFileSync('js/ir-core.js','utf8');
assert.doesNotMatch(core,/inst\.stackArgsUnknown \|\| inst\.stackArgsMayContainPointers/);
console.log('issues #526 #537 #538 #539 regressions passed');
